# Build indexed lookup dictionaries
VM_BY_REG = {}
VM_BY_CLEAN = {}
VM_BY_EXACT = {}

for name, reg, vis, mis in VERIFIED_DATA_ENTRIES:
    entry = {'name': name, 'reg_no': reg, 'vis': vis, 'mis': mis}
    if reg:
        VM_BY_REG[str(reg).strip()] = entry
    ek = normalize_text(name).lower()
    VM_BY_EXACT[ek] = entry
    ck = clean_key(name)
    VM_BY_CLEAN[ck] = entry

def lookup_verified_vm(name, reg_no=None, official_name=None):
    # 1. Reg No lookup
    if reg_no and str(reg_no).strip() in VM_BY_REG:
        e = VM_BY_REG[str(reg_no).strip()]
        return e['vis'], e['mis'], 'reg_match'
        
    # 2. Exact name lookup
    for cand in [name, official_name]:
        if not cand: continue
        ek = normalize_text(cand).lower()
        if ek in VM_BY_EXACT:
            e = VM_BY_EXACT[ek]
            return e['vis'], e['mis'], 'exact_match'
            
    # 3. Clean key lookup
    for cand in [name, official_name]:
        if not cand: continue
        ck = clean_key(cand)
        if ck in VM_BY_CLEAN:
            e = VM_BY_CLEAN[ck]
            return e['vis'], e['mis'], 'clean_match'
            
    return None, None, None

