def update_excel(filepath):
    print(f"Updating {filepath}...")
    wb = openpyxl.load_workbook(filepath)
    ws = wb.active

    # Styling definitions
    header_font = Font(name="Arial", size=11, bold=True, color="FFFFFF")
    header_fill = PatternFill(start_color="1F4E79", end_color="1F4E79", fill_type="solid")
    header_align = Alignment(horizontal="center", vertical="center", wrap_text=True)

    regular_font = Font(name="Arial", size=10)
    center_align = Alignment(horizontal="center", vertical="center")
    left_wrap_align = Alignment(horizontal="left", vertical="center", wrap_text=True)

    thin_border_side = Side(border_style="thin", color="D9D9D9")
    border = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)

    zebra_fill = PatternFill(start_color="F9FAFB", end_color="F9FAFB", fill_type="solid")
    white_fill = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")

    # Column H: Алсын хараа
    ws.cell(row=1, column=8, value="Алсын хараа")
    c_h = ws.cell(row=1, column=8)
    c_h.font = header_font
    c_h.fill = header_fill
    c_h.alignment = header_align
    c_h.border = border

    # Column I: Эрхэм зорилго
    ws.cell(row=1, column=9, value="Эрхэм зорилго")
    c_i = ws.cell(row=1, column=9)
    c_i.font = header_font
    c_i.fill = header_fill
    c_i.alignment = header_align
    c_i.border = border

    # Rows
    for r in range(2, ws.max_row + 1):
        rank = ws.cell(row=r, column=1).value
        try:
            rank = int(rank)
        except (ValueError, TypeError):
            continue

        vis, mis = VISION_MISSION_DATA.get(rank, ("-", "-"))

        cell_h = ws.cell(row=r, column=8, value=vis)
        cell_i = ws.cell(row=r, column=9, value=mis)

        row_fill = zebra_fill if (r % 2 == 0) else white_fill

        for cell, val in [(cell_h, vis), (cell_i, mis)]:
            cell.font = regular_font
            cell.border = border
            cell.fill = row_fill
            if val == "-":
                cell.alignment = center_align
            else:
                cell.alignment = left_wrap_align

    # Adjust column widths
    ws.column_dimensions['H'].width = 45
    ws.column_dimensions['I'].width = 50

    wb.save(filepath)
    print(f"Successfully saved {filepath} with 9 columns.")

